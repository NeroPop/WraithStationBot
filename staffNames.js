// HOW TO EDIT THIS LIST
//   To ADD a name:    add a new line with the name in quote marks, followed by a comma.
//   To REMOVE a name: delete its line.
//
// Then save, commit and push to GitHub, and restart the server on Wispbyte.
//
// Notes:
//   - Write each name the way the bot should SAY it. If you write 'Steve' here,
//     then "silly steve", "SILLY STEVE" and "silly Steve" all get the reply "Silly Steve".
//   - Capital letters in what people type do not matter.
//   - Keep each name inside quote marks, and do not forget the comma at the end of the line.

